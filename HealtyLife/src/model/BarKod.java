package model;

public class BarKod {
	
	private String stanje;
    private int barKod;
    
    /**
     * Default constructor
     */
    public BarKod() {
    }
    
	public String getStanje() {
		return stanje;
	}
	public void setStanje(String stanje) {
		this.stanje = stanje;
	}
	public int getBarKod() {
		return barKod;
	}
	public void setBarKod(int barKod) {
		this.barKod = barKod;
	}
    
}
